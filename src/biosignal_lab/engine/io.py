"""Explicit-metadata scientific interchange without pickle or unit inference."""

from __future__ import annotations
import json
import math
from pathlib import Path
import numpy as np
from .model import Signal


def save_signal(signal: Signal, path):
    """Exclusive-create NPZ archive with JSON metadata; never overwrite results."""
    metadata = {
        "schema_version": 1,
        "sfreq": signal.sfreq,
        "channels": signal.channels,
        "modality": signal.modality,
        "unit": signal.unit,
        "reference": signal.reference,
        "metadata": dict(signal.metadata),
        "history": signal.history,
    }
    encoded = json.dumps(metadata, allow_nan=False)
    with Path(path).open("xb") as target:
        np.savez_compressed(target, data=signal.data, metadata=np.array(encoded))


def load_signal(path, *, max_bytes=256_000_000):
    """NPZ generated by save_signal; bound uncompressed archive size first."""
    import zipfile

    path = Path(path)
    if path.stat().st_size > max_bytes:
        raise ValueError("Signal archive exceeds resource limit")
    with zipfile.ZipFile(path) as archive:
        entries = archive.infolist()
        if (
            {entry.filename for entry in entries} != {"data.npy", "metadata.npy"}
            or len(entries) != 2
            or sum(e.file_size for e in entries) > max_bytes
        ):
            raise ValueError("Invalid signal archive members or expanded resource limit")
        # Bound declared NPY shapes too: a tiny malicious header can claim a huge array.
        allocation = 0
        for entry in entries:
            with archive.open(entry) as member:
                version = np.lib.format.read_magic(member)
                reader = {
                    (1, 0): np.lib.format.read_array_header_1_0,
                    (2, 0): np.lib.format.read_array_header_2_0,
                }.get(version)
                if reader is None:
                    raise ValueError("Unsupported NPY member version")
                shape, _, dtype = reader(member)
                if entry.filename == "data.npy":
                    if len(shape) != 2 or min(shape) < 1 or dtype.kind not in "fiu":
                        raise ValueError("NPY data must be a nonempty real numeric matrix")
                    # Signal converts to float64: uint8 input needs eight times its storage.
                    allocation += math.prod(shape) * max(dtype.itemsize, 8)
                else:
                    if shape != () or dtype.kind not in "US" or dtype.itemsize > 1_000_000:
                        raise ValueError("NPY metadata must be bounded scalar text")
                    allocation += dtype.itemsize
                if dtype.hasobject or allocation > max_bytes:
                    raise ValueError("Unsafe NPY dtype or declared allocation limit")
    with np.load(path, allow_pickle=False) as loaded:
        metadata = json.loads(str(loaded["metadata"].item()))
        if metadata.pop("schema_version", None) != 1:
            raise ValueError("Unsupported signal schema")
        return Signal(data=loaded["data"], **metadata)


def load_mat(
    path, *, data_key, sfreq, channels, modality, unit, reference=None, max_bytes=256_000_000
):
    """MAT v4/v5/v7.2 numeric matrix; metadata explicitly supplied by caller.

    MATLAB v7.3/HDF5 is not silently interpreted by this adapter.
    """
    from scipy.io import loadmat, whosmat

    path = Path(path)
    if path.stat().st_size > max_bytes:
        raise ValueError("MAT file exceeds resource limit")
    declarations = [item for item in whosmat(path) if item[0] == data_key]
    if len(declarations) != 1:
        raise ValueError("MAT data key missing or duplicated")
    _, shape, kind = declarations[0]
    allowed = {
        "double",
        "single",
        "int8",
        "uint8",
        "int16",
        "uint16",
        "int32",
        "uint32",
        "int64",
        "uint64",
    }
    # Reserve worst-case complex-double storage; Signal separately rejects complex data.
    if (
        len(shape) != 2
        or min(shape) < 1
        or kind not in allowed
        or math.prod(shape) * 16 > max_bytes
    ):
        raise ValueError("MAT data must be a bounded numeric matrix")
    values = loadmat(path, variable_names=[data_key])
    if data_key not in values:
        raise ValueError("MAT data key missing")
    return Signal(
        values[data_key],
        sfreq,
        tuple(channels),
        modality,
        unit,
        reference,
        {"format": "MAT", "data_key": data_key, "source": str(Path(path).name)},
    )


def load_mne(path, *, modality="eeg", max_samples=20_000_000):
    """MNE EDF/BDF/GDF/FIF adapter; retain all selected modality channel labels.

    All electrical samples are explicitly converted from MNE volts to uV.
    No mixed-modality channel is silently included. Annotations retained.
    """
    import mne

    suffix = Path(path).suffix.lower()
    readers = {
        ".edf": mne.io.read_raw_edf,
        ".bdf": mne.io.read_raw_bdf,
        ".gdf": mne.io.read_raw_gdf,
        ".fif": mne.io.read_raw_fif,
    }
    if suffix not in readers or modality not in {"eeg", "emg", "ecg", "eog"}:
        raise ValueError("Supported MNE formats EDF/BDF/GDF/FIF and electrical modality required")
    options = {"infer_types": True} if suffix in {".edf", ".bdf"} else {}
    raw = readers[suffix](path, preload=False, verbose="ERROR", **options)
    try:
        indices = [i for i, kind in enumerate(raw.get_channel_types()) if kind == modality]
        if not indices:
            raise ValueError("No channels explicitly typed as requested modality")
        if raw.n_times * len(indices) > max_samples:
            raise ValueError("Recording exceeds resource limit; crop explicitly with MNE first")
        metadata = {
            "format": suffix[1:],
            "source": Path(path).name,
            "mne_version": mne.__version__,
            "channel_types": [modality] * len(indices),
            "annotations": [
                {"onset_s": float(a), "duration_s": float(b), "description": str(c)}
                for a, b, c in zip(
                    raw.annotations.onset, raw.annotations.duration, raw.annotations.description
                )
            ],
            "bad_channels": list(raw.info["bads"]),
            "mne_custom_ref_applied": bool(raw.info["custom_ref_applied"]),
            "reference_note": "Acquisition reference not inferred; inspect source documentation",
            "typing_note": "EDF/BDF types inferred from labels by MNE; unknown labels may default to EEG. Verify source metadata; no physiological identity inferred.",
        }
        return Signal(
            raw.get_data(picks=indices) * 1e6,
            float(raw.info["sfreq"]),
            tuple(raw.ch_names[i] for i in indices),
            modality,
            "uV",
            None,
            metadata,
        )
    finally:
        raw.close()


def save_hdf5(signal: Signal, path):
    """Exclusive-create versioned HDF5 with JSON metadata, no arbitrary objects."""
    import h5py

    metadata = {
        "schema_version": 1,
        "sfreq": signal.sfreq,
        "channels": signal.channels,
        "modality": signal.modality,
        "unit": signal.unit,
        "reference": signal.reference,
        "metadata": dict(signal.metadata),
        "history": signal.history,
    }
    encoded = json.dumps(metadata, allow_nan=False)
    with h5py.File(path, "x") as target:
        target.create_dataset("data", data=signal.data, compression="gzip")
        target.attrs["biosignal_metadata"] = encoded


def load_hdf5(path, *, max_bytes=256_000_000):
    """Read engine HDF5 schema; reject external/virtual datasets and oversize data."""
    import h5py

    with h5py.File(path, "r") as source:
        if list(source.keys()) != ["data"] or not isinstance(
            source.get("data", getlink=True), h5py.HardLink
        ):
            raise ValueError("HDF5 must contain only a local data dataset")
        data = source["data"]
        if (
            not isinstance(data, h5py.Dataset)
            or data.is_virtual
            or data.external
            or data.dtype.kind not in "fiu"
            or len(data.shape) != 2
            or data.size * max(data.dtype.itemsize, 8) > max_bytes
        ):
            raise ValueError("Invalid HDF5 dataset or expanded resource limit")
        encoded = source.attrs.get("biosignal_metadata", "")
        if not isinstance(encoded, str) or len(encoded) > 1_000_000:
            raise ValueError("Missing or oversized HDF5 metadata")
        metadata = json.loads(encoded)
        if metadata.pop("schema_version", None) != 1:
            raise ValueError("Unsupported HDF5 signal schema")
        return Signal(data[...], **metadata)
